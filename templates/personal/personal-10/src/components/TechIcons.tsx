export const getTechIcon = (key: string, className = "w-9 h-9") => {
  switch (key.toLowerCase()) {
    case 'html5':
    case 'html':
      return <Html5Icon className={className} />;
    case 'css3':
    case 'css':
      return <Css3Icon className={className} />;
    case 'javascript':
    case 'js':
      return <JsIcon className={className} />;
    case 'react':
    case 'react.js':
      return <ReactIcon className={className} />;
    case 'nextjs':
    case 'next.js':
      return <NextJsIcon className={className} />;
    case 'nodejs':
    case 'node.js':
      return <NodeJsIcon className={className} />;
    case 'mongodb':
      return <MongoDbIcon className={className} />;
    case 'tailwind':
    case 'tailwindcss':
    case 'tailwind css':
      return <TailwindIcon className={className} />;
    case 'typescript':
    case 'ts':
      return <TypeScriptIcon className={className} />;
    case 'express':
    case 'express.js':
      return <ExpressIcon className={className} />;
    case 'redux':
      return <ReduxIcon className={className} />;
    case 'git':
      return <GitIcon className={className} />;
    case 'docker':
      return <DockerIcon className={className} />;
    case 'figma':
      return <FigmaIcon className={className} />;
    case 'python':
      return <PythonIcon className={className} />;
    case 'postgresql':
    case 'postgres':
      return <PostgreSqlIcon className={className} />;
    default:
      return <ReactIcon className={className} />;
  }
};
